-- Esquema inicial de VinculaTec, alineado con backend/app/models/entities.py.
-- El backend accede con PostgreSQL; las tablas expuestas por PostgREST quedan protegidas por RLS.

CREATE TABLE public.organizations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    type varchar(30) NOT NULL,
    size varchar(30),
    sector varchar(120),
    rfc varchar(13),
    description text,
    city varchar(120),
    state varchar(120),
    website varchar(255),
    verified boolean NOT NULL,
    latitude double precision,
    longitude double precision,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX ix_organizations_name ON public.organizations (name);
CREATE INDEX ix_organizations_type ON public.organizations (type);
CREATE INDEX ix_organizations_state ON public.organizations (state);

CREATE TABLE public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    hashed_password varchar(255) NOT NULL,
    full_name varchar(200) NOT NULL,
    role varchar(30) NOT NULL,
    is_active boolean NOT NULL,
    organization_id integer REFERENCES public.organizations(id),
    career varchar(150),
    semester integer,
    skills json NOT NULL,
    bio text,
    portfolio_url varchar(255),
    rating_avg double precision NOT NULL,
    rating_count integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX ix_users_email ON public.users (email);
CREATE INDEX ix_users_role ON public.users (role);
CREATE INDEX ix_users_career ON public.users (career);

CREATE TABLE public.careers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL UNIQUE,
    created_by_org_id integer REFERENCES public.organizations(id),
    created_at timestamptz NOT NULL
);
CREATE INDEX ix_careers_name ON public.careers (name);

CREATE TABLE public.university_careers (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL REFERENCES public.organizations(id),
    career_id integer NOT NULL REFERENCES public.careers(id),
    CONSTRAINT uq_university_careers_organization_id UNIQUE (organization_id, career_id)
);
CREATE INDEX ix_university_careers_organization_id ON public.university_careers (organization_id);
CREATE INDEX ix_university_careers_career_id ON public.university_careers (career_id);

CREATE TABLE public.capabilities (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL REFERENCES public.organizations(id),
    type varchar(30) NOT NULL,
    name varchar(200) NOT NULL,
    description text,
    tags json NOT NULL,
    contact_user_id integer REFERENCES public.users(id),
    available boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX ix_capabilities_organization_id ON public.capabilities (organization_id);
CREATE INDEX ix_capabilities_type ON public.capabilities (type);

CREATE TABLE public.challenges (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL REFERENCES public.organizations(id),
    created_by_id integer NOT NULL REFERENCES public.users(id),
    title varchar(200) NOT NULL,
    summary varchar(500) NOT NULL,
    description text NOT NULL,
    category varchar(120) NOT NULL,
    tags json NOT NULL,
    required_disciplines json NOT NULL,
    min_disciplines integer NOT NULL,
    modalities json NOT NULL,
    budget_mxn double precision,
    offers_stipend boolean NOT NULL,
    duration_weeks integer,
    deadline date,
    confidentiality varchar(30) NOT NULL,
    ip_model varchar(30) NOT NULL,
    status varchar(30) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX ix_challenges_organization_id ON public.challenges (organization_id);
CREATE INDEX ix_challenges_title ON public.challenges (title);
CREATE INDEX ix_challenges_category ON public.challenges (category);
CREATE INDEX ix_challenges_status ON public.challenges (status);

CREATE TABLE public.nda_acceptances (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users(id),
    challenge_id integer NOT NULL REFERENCES public.challenges(id),
    accepted_at timestamptz NOT NULL,
    CONSTRAINT uq_nda_acceptances_user_id UNIQUE (user_id, challenge_id)
);
CREATE INDEX ix_nda_acceptances_user_id ON public.nda_acceptances (user_id);
CREATE INDEX ix_nda_acceptances_challenge_id ON public.nda_acceptances (challenge_id);

CREATE TABLE public.teams (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    description text,
    university_id integer REFERENCES public.organizations(id),
    created_by_id integer NOT NULL REFERENCES public.users(id),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE TABLE public.team_members (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id integer NOT NULL REFERENCES public.teams(id),
    user_id integer NOT NULL REFERENCES public.users(id),
    role varchar(30) NOT NULL,
    joined_at timestamptz NOT NULL,
    CONSTRAINT uq_team_members_team_id UNIQUE (team_id, user_id)
);
CREATE INDEX ix_team_members_team_id ON public.team_members (team_id);
CREATE INDEX ix_team_members_user_id ON public.team_members (user_id);

CREATE TABLE public.proposals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id integer NOT NULL REFERENCES public.challenges(id),
    team_id integer NOT NULL REFERENCES public.teams(id),
    approach text NOT NULL,
    work_plan text,
    estimated_weeks integer,
    status varchar(30) NOT NULL,
    feedback text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uq_proposals_team_id UNIQUE (team_id, challenge_id)
);
CREATE INDEX ix_proposals_challenge_id ON public.proposals (challenge_id);
CREATE INDEX ix_proposals_team_id ON public.proposals (team_id);
CREATE INDEX ix_proposals_status ON public.proposals (status);

CREATE TABLE public.milestones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id integer NOT NULL REFERENCES public.challenges(id),
    title varchar(200) NOT NULL,
    description text,
    due_date date,
    status varchar(30) NOT NULL,
    deliverable_url varchar(500),
    company_comment text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
CREATE INDEX ix_milestones_challenge_id ON public.milestones (challenge_id);

CREATE TABLE public.messages (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id integer NOT NULL REFERENCES public.challenges(id),
    author_id integer NOT NULL REFERENCES public.users(id),
    body text NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE INDEX ix_messages_challenge_id ON public.messages (challenge_id);
CREATE INDEX ix_messages_created_at ON public.messages (created_at);

CREATE TABLE public.reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id integer NOT NULL REFERENCES public.challenges(id),
    reviewer_id integer NOT NULL REFERENCES public.users(id),
    reviewee_id integer NOT NULL REFERENCES public.users(id),
    score integer NOT NULL,
    comment text,
    created_at timestamptz NOT NULL,
    CONSTRAINT uq_reviews_challenge_id UNIQUE (challenge_id, reviewer_id, reviewee_id)
);
CREATE INDEX ix_reviews_challenge_id ON public.reviews (challenge_id);
CREATE INDEX ix_reviews_reviewee_id ON public.reviews (reviewee_id);

CREATE TABLE public.notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.users(id),
    title varchar(200) NOT NULL,
    body text,
    link varchar(255),
    read boolean NOT NULL,
    created_at timestamptz NOT NULL
);
CREATE INDEX ix_notifications_user_id ON public.notifications (user_id);
CREATE INDEX ix_notifications_read ON public.notifications (read);

